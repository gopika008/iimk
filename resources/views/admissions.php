                                    <div class="admission-policy-block-header">
                                        <div>
                                            <span>Selection Process</span>
                                            <h3>Three-Stage Selection Process</h3>
                                        </div>

                                        <p>
                                            IIM Kozhikode adopts a three-stage selection process for admission to the PGP 2026-28 batch.
                                        </p>
                                    </div>

                                    <div class="admission-policy-body">

                                        <div class="admission-process-timeline">

                                            <article class="admission-process-step">
                                                <div class="admission-process-marker">
                                                    <span>01</span>
                                                </div>

                                                <div class="admission-process-content">
                                                    <div class="admission-process-label">Stage 1</div>
                                                    <h4>Online Registration</h4>

                                                    <p>
                                                        All candidates who have opted for IIM Kozhikode in their CAT applications and are fulfilling
                                                        the minimum eligibility criteria would receive an email for online registration for admissions
                                                        to IIM Kozhikode.
                                                    </p>

                                                    <p>
                                                        Only those candidates who have successfully completed the online registration process for
                                                        IIM Kozhikode are considered for Stage 2.
                                                    </p>

                                                    <a href="https://iimk.ac.in/apps/Admission/PGP/Registration" target="_blank" rel="noopener" class="admission-process-btn admission-process-btn-green">
                                                        Register Stage 1
                                                        <i class="bi bi-box-arrow-up-right"></i>
                                                    </a>
                                                </div>
                                            </article>

                                            <article class="admission-process-step">
                                                <div class="admission-process-marker">
                                                    <span>02</span>
                                                </div>

                                                <div class="admission-process-content">
                                                    <div class="admission-process-label">Stage 2</div>
                                                    <h4>Shortlisting for WAT and PI</h4>

                                                    <p>
                                                        In Stage 2, a shortlist of candidates in each reservation category would be prepared based
                                                        on an Aggregate Index Score.
                                                    </p>

                                                    <p>
                                                        The Aggregate Index Score is computed based on performance in CAT, academic performance
                                                        in Class X and XII, work experience and gender / academic diversity.
                                                    </p>

                                                    <a href="https://iimk.ac.in/apps/Admission/PGP/Login" target="_blank" rel="noopener" class="admission-process-btn admission-process-btn-blue">
                                                        Stage 2 Shortlist
                                                        <i class="bi bi-box-arrow-up-right"></i>
                                                    </a>
                                                </div>
                                            </article>

                                            <article class="admission-process-step">
                                                <div class="admission-process-marker">
                                                    <span>03</span>
                                                </div>

                                                <div class="admission-process-content">
                                                    <div class="admission-process-label">Stage 3</div>
                                                    <h4>PI, WAT and Final Merit List</h4>

                                                    <p>
                                                        In Stage 3, the short-listed candidates would be asked to appear for Personal Interview
                                                        and Written Ability Test.
                                                    </p>

                                                    <p>
                                                        After the conclusion of the PI and WAT process, a category-wise merit list would be prepared
