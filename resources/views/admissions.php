                                    <div>
                                        <span>Selection Process</span>
                                        <h3>Three-stage admission process</h3>
                                        <p>
                                            The PGP admission process includes registration of eligible candidates,
                                            shortlisting for Written Ability Test and Personal Interview, and final selection
                                            based on CAT, PI, WAT and resume score.
                                        </p>
                                    </div>
